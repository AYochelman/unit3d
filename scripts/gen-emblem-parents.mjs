#!/usr/bin/env node
/**
 * Writes lib/emblemParent.generated.ts — battalion slug → its brigade's slug.
 *
 *   npm run emblems:parents
 *
 * Most battalions have no insignia of their own on Wikimedia Commons. Rather
 * than copy the brigade's PNG under 118 more names, EmblemImage falls back to
 * the parent's file, and this is the map it reads. Re-run it after adding or
 * renaming a unit in lib/units-hierarchy.ts.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "lib", "units-hierarchy.ts");
const OUT = path.join(ROOT, "lib", "emblemParent.generated.ts");

// The hierarchy is TypeScript, and this runs as plain node, so read the slugs
// out of the source rather than importing it. Brigades carry a `battalions`
// array; everything between one `battalions: [` and its closing bracket belongs
// to the brigade whose slug came last.
const src = fs.readFileSync(SRC, "utf8");
const pairs = [];
const SLUG = /slug:\s*"([^"]+)"/g;
let brigade = null;
let depth = 0;
let inBattalions = false;

for (const line of src.split("\n")) {
  if (!inBattalions && /battalions:\s*\[/.test(line)) {
    inBattalions = true;
    depth = 0;
  }
  if (inBattalions) {
    // The brigade's emblem file is prefixed, the battalion's is not — that is
    // how CatalogClient asks for each of them.
    for (const m of line.matchAll(SLUG)) if (brigade) pairs.push([m[1], `brigade-${brigade}`]);
    depth += (line.match(/\[/g) ?? []).length - (line.match(/\]/g) ?? []).length;
    if (depth <= 0 && !/battalions:\s*\[\s*$/.test(line)) inBattalions = false;
    continue;
  }
  const m = [...line.matchAll(SLUG)].pop();
  if (m) brigade = m[1];
}

const body = [
  "// Auto-generated by scripts/gen-emblem-parents.mjs — DO NOT EDIT BY HAND.",
  "//",
  "// A battalion whose own insignia is not on Wikimedia Commons shows its",
  "// brigade's emblem rather than a drawn placeholder. Mapping it here instead",
  "// of copying the brigade PNG under 118 more names keeps public/emblems at one",
  "// file per real image.",
  "",
  "export const EMBLEM_PARENT: Record<string, string> = {",
  ...pairs.map(([b, p]) => `  ${JSON.stringify(b)}: ${JSON.stringify(p)},`),
  "};",
  "",
].join("\n");

fs.writeFileSync(OUT, body, "utf8");
console.log(`  ${pairs.length} גדודים מופו לחטיבה שלהם`);
